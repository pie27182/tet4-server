#!/usr/bin/env python3
"""Build names/<module>.tsv from the Ghidra decompilation of HgCom3.dll.

Two sources, both machine-derived from work/decompiled/HgCom3.dll.c:

1. Message classes: in a constructor the code stores
       *param_1 = Cmd_XXX::vftable;
       param_1[2] = 0x<message id>;
   Pairs of those give "id -> class name".
2. The X2M registration table: the init routine assigns
       pcVar6 = FUN_<converter>;
       iVar4  = 0x<message id>;
       FUN_60121a40(puVar2, iVar4, uVar5, (int)pcVar6, ...);
   Pairs of those give "id -> converter address".

A converter with a known id becomes "<Class>::Converter". Existing entries in
names/<module>.tsv are preserved and win over generated ones.

Usage: python3 tools/build_name_map.py [module]
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DECOMPILED = ROOT / "work" / "decompiled"
NAMES = ROOT / "names"

CLASS_RE = re.compile(r"\*param_1 = (Cmd_[A-Za-z0-9_]+)::vftable;")
ID_RE = re.compile(r"param_1\[2\] = (0x[0-9a-fA-F]+);")
CONV_RE = re.compile(r"pcVar6 = (FUN_[0-9a-fA-F]+);")
ID_ASSIGN_RE = re.compile(r"iVar4 = (0x[0-9a-fA-F]+);")
REGISTER_RE = re.compile(r"FUN_60121a40\(")


def id_to_class(text: str) -> dict[int, str]:
    """Find constructors and pair the vftable class with the message id."""
    mapping: dict[int, str] = {}
    lines = text.splitlines()
    for i, line in enumerate(lines):
        m = CLASS_RE.search(line)
        if not m:
            continue
        for j in range(i, min(i + 40, len(lines))):
            n = ID_RE.search(lines[j])
            if n:
                mapping.setdefault(int(n.group(1), 16), m.group(1))
                break
    return mapping


def id_to_converter(text: str) -> dict[int, str]:
    """Walk the registration routine tracking the last converter and message id."""
    mapping: dict[int, str] = {}
    converter: str | None = None
    message_id: int | None = None
    for line in text.splitlines():
        m = CONV_RE.search(line)
        if m:
            converter = m.group(1)
        n = ID_ASSIGN_RE.search(line)
        if n:
            message_id = int(n.group(1), 16)
        if REGISTER_RE.search(line) and converter and message_id is not None:
            mapping.setdefault(message_id, converter)
            converter, message_id = None, None
    return mapping


def read_existing(path: Path) -> list[str]:
    if not path.exists():
        return []
    return [line for line in path.read_text().splitlines() if line.strip()]


def main() -> int:
    module = sys.argv[1] if len(sys.argv) > 1 else "HgCom3.dll"
    source = DECOMPILED / f"{module}.c"
    if not source.exists():
        print(f"no decompilation at {source}; run tools/export.sh first", file=sys.stderr)
        return 1
    text = source.read_text(errors="replace")

    classes = id_to_class(text)
    converters = id_to_converter(text)
    print(f"message ids with a class name: {len(classes)}")
    print(f"registered converters:         {len(converters)}")

    existing = read_existing(NAMES / f"{module}.tsv")
    manual_names = set()
    manual_addresses = set()
    for line in existing:
        if line.startswith("#") or "\t" not in line:
            continue
        address, name = line.split("\t", 1)
        manual_addresses.add(address.strip().lower())
        manual_names.add(name.strip())

    generated = []
    matched = 0
    for message_id, converter in sorted(converters.items()):
        class_name = classes.get(message_id)
        if not class_name:
            continue
        matched += 1
        address = "0x" + converter.split("_", 1)[1].lower()
        name = f"{class_name}::Converter"
        if address in manual_addresses or name in manual_names:
            continue
        generated.append(f"{address}\t{name}")

    header = [
        f"# Reconstructed names for {module}.",
        "# Generated by tools/build_name_map.py from the X2M registration table and",
        "# the message constructors in the Ghidra decompilation, plus manual entries.",
        "# These are NOT original symbols; the binary only kept class names.",
    ]
    out = NAMES / f"{module}.tsv"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(header + existing + generated) + "\n")
    print(f"converters named: {matched}, new entries: {len(generated)}, file: {out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
